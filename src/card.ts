// Lesson card window controller (WP62): Muse Image recap for older users.
// Displays an illustrated recap card after a lesson ends well.
// Listens for the "lesson-card" Tauri event from Rust with payload
// `{ title: string, steps: string[], imagePath: string }`.
// Outside Tauri, displays a placeholder card.
// All user-facing strings come from `src/i18n` (invariant 7).

import type { LocaleKey } from "./i18n/index.ts";

// The locale lookup comes from the page entry (src/card-page.ts): importing src/i18n here
// would load the locale JSON, which Node's test runner cannot import.
let t = (key: LocaleKey): string => key;
let getLocale = (): string => "en";
export function setCardI18n(translate: (key: LocaleKey) => string, locale: () => string): void {
  t = translate;
  getLocale = locale;
}

/** Lesson card data model generated by Rust + Muse Image. */
export interface LessonCard {
  readonly title: string;
  readonly steps: readonly string[];
  readonly imagePath: string;
}

/** Name of the Tauri event carrying a new lesson card. */
export const LESSON_CARD_EVENT = "lesson-card";
/** The event the card page sends once it listens for cards. */
export const CARD_READY_EVENT = "card-ready";

/**
 * Validates and parses an untrusted event payload into a `LessonCard`.
 * Returns `null` if any field is missing, not a string, or empty.
 * Never throws.
 */
export function parseLessonCard(raw: unknown): LessonCard | null {
  try {
    if (typeof raw !== "object" || raw === null || Array.isArray(raw)) {
      return null;
    }
    const { title, steps, imagePath } = raw as Record<string, unknown>;

    if (typeof title !== "string" || !title.trim()) {
      return null;
    }
    if (typeof imagePath !== "string" || !imagePath.trim()) {
      return null;
    }
    if (!Array.isArray(steps) || steps.length === 0) {
      return null;
    }

    const cleanSteps: string[] = [];
    for (const step of steps) {
      if (typeof step !== "string" || !step.trim()) {
        return null;
      }
      cleanSteps.push(step.trim());
    }

    return {
      title: title.trim(),
      steps: cleanSteps,
      imagePath: imagePath.trim(),
    };
  } catch {
    return null;
  }
}

/**
 * Returns a localized placeholder lesson card shown outside Tauri
 * or before a card event arrives.
 */
export function getPlaceholderCard(): LessonCard {
  return {
    title: t("card.placeholder_title"),
    steps: [
      t("card.placeholder_step_1"),
      t("card.placeholder_step_2"),
      t("card.placeholder_step_3"),
    ],
    imagePath: "",
  };
}

/**
 * Converts a local file path into a displayable asset URL in Tauri,
 * or returns it directly if it is already a web / data URL.
 */
export async function resolveCardImageUrl(imagePath: string): Promise<string> {
  const trimmed = imagePath.trim();
  if (!trimmed) {
    return "";
  }
  if (
    trimmed.startsWith("data:") ||
    trimmed.startsWith("http://") ||
    trimmed.startsWith("https://") ||
    trimmed.startsWith("asset://") ||
    trimmed.startsWith("/")
  ) {
    return trimmed;
  }

  if (typeof window !== "undefined" && "__TAURI_INTERNALS__" in window) {
    try {
      const { convertFileSrc } = await import("@tauri-apps/api/core");
      if (typeof convertFileSrc === "function") {
        return convertFileSrc(trimmed);
      }
    } catch {
      // Fall through to returning the original path
    }
  }

  return trimmed;
}

/** Triggers the standard system print dialog. */
export function printCard(): void {
  if (typeof window !== "undefined" && typeof window.print === "function") {
    window.print();
  }
}

/** Closes the card window via Tauri API or fallback to window.close(). */
export async function closeCard(): Promise<void> {
  if (typeof window !== "undefined" && "__TAURI_INTERNALS__" in window) {
    try {
      const { getCurrentWindow } = await import("@tauri-apps/api/window");
      const current = getCurrentWindow();
      if (current && typeof current.close === "function") {
        await current.close();
        return;
      }
    } catch {
      // Fallback
    }
  }

  if (typeof window !== "undefined" && typeof window.close === "function") {
    window.close();
  }
}

/** Escapes special HTML characters to prevent XSS. */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

