export type CaptionedCardSaver = (args: {
  readonly id: string;
  readonly pngBase64: string;
}) => Promise<void>;

/**
 * Sends the captioned keepsake PNG to Rust at most once per `id`.
 * Skips when `id` is absent or the decoded PNG exceeds 8 MiB; logs failures
 * with `console.warn` only so the window stays usable.
 */
export async function sendCaptionedCardOnce(
  rawId: string | undefined,
  dataUrl: string,
  savedIds: Set<string>,
  customSave?: CaptionedCardSaver,
): Promise<boolean> {
  const decision = prepareCaptionedSavePayload(rawId, dataUrl);
  if (!decision.ok) {
    if (decision.reason === "too-large") {
      console.warn("[card] captioned PNG exceeds 8 MiB; skipping save");
    } else if (decision.reason === "invalid-data-url") {
      console.warn("[card] invalid captioned PNG data URL; skipping save");
    }
    return false;
  }

  const { id, pngBase64 } = decision;
  if (savedIds.has(id)) {
    return false;
  }

  const hasTauri = typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;
  if (!customSave && !hasTauri) {
    return false;
  }

  savedIds.add(id);
  try {
    if (customSave) {
      await customSave({ id, pngBase64 });
    } else {
      const { invoke } = await import("@tauri-apps/api/core");
      await invoke("card_save_captioned", { id, pngBase64 });
    }
    return true;
  } catch (error) {
    console.warn("[card] failed to save captioned card:", error);
    return false;
  }
}

/**
 * Controller interface returned by `mountLessonCard`.
 */
export interface CardController {
  getCard(): LessonCard;
  setCard(card: LessonCard): Promise<void>;
  handleRaw(raw: unknown): boolean;
  destroy(): void;
}

export interface MountCardOptions {
  readonly initialCard?: LessonCard;
  readonly isTauri?: boolean;
  readonly savedIds?: Set<string>;
  readonly saveCaptioned?: CaptionedCardSaver;
}

/**
 * Mounts the lesson card UI inside `container`.
 */
export function mountLessonCard(
  container: HTMLElement,
  options: MountCardOptions = {},
): CardController {
  let currentCard: LessonCard = options.initialCard ?? getPlaceholderCard();
  let destroyed = false;
  let renderGeneration = 0;
  let imgCreditsMuse = false;
  const savedIds = options.savedIds ?? new Set<string>();

  const layout = document.createElement("article");
  layout.className = "card-layout";

  // Header: the keepsake preview beside the badge and title (stacks in a narrow window)
  const header = document.createElement("header");
  header.className = "card-header";

  const mediaPanel = document.createElement("div");
  mediaPanel.className = "card-media-panel";

  const imgWrapper = document.createElement("div");
  imgWrapper.className = "card-image-wrapper";

  // The alt text says what the picture shows: the title next to it is read out already.
  const img = document.createElement("img");
  img.id = "card-image";
  img.className = "card-image";
  img.alt = t("card.image_alt");
  img.style.display = "none";

  const placeholderArt = document.createElement("div");
  placeholderArt.id = "card-placeholder-art";
  placeholderArt.className = "card-placeholder-art";
  placeholderArt.innerHTML = PLACEHOLDER_MATE_SVG;

  img.addEventListener("error", () => {
    layout.className = "card-layout";
    img.style.display = "none";
    placeholderArt.style.display = "flex";
    credits.hidden = true;
  });

  img.addEventListener("load", () => {
    if (!destroyed && img.getAttribute("src")) {
      img.style.display = "block";
      placeholderArt.style.display = "none";
      credits.hidden = !imgCreditsMuse;
    }
  });

  imgWrapper.append(img, placeholderArt);
  mediaPanel.append(imgWrapper);

  const heading = document.createElement("div");
  heading.className = "card-heading";

  const badge = document.createElement("span");
  badge.className = "card-badge";
  badge.textContent = t("card.recap_badge");

  const titleEl = document.createElement("h1");
  titleEl.id = "card-title";
  titleEl.className = "card-title";
  titleEl.textContent = currentCard.title;

  heading.append(badge, titleEl);
  header.append(mediaPanel, heading);

  const stepsList = document.createElement("ol");
  stepsList.id = "card-steps";
  stepsList.className = "card-steps";

  const renderSteps = (steps: readonly string[]): void => {
    stepsList.replaceChildren(
      ...steps.map((stepText, idx) => {
        const li = document.createElement("li");
        li.className = "card-step";

        const numSpan = document.createElement("span");
        numSpan.className = "card-step-num";
        numSpan.setAttribute("aria-hidden", "true");
        numSpan.textContent = String(idx + 1);

        const textSpan = document.createElement("span");
        textSpan.className = "card-step-text";
        textSpan.textContent = stepText;

        li.append(numSpan, textSpan);
        return li;
      }),
    );
  };

  renderSteps(currentCard.steps);

  // Credit line under the steps (printed too). Shown with the picture it credits: the
  // placeholder's Mate is no Muse Image picture.
  const credits = document.createElement("p");
  credits.id = "card-credits";
  credits.className = "card-credits";
  credits.hidden = true;

  // The family's note at the bottom, in the card's handwritten face; no note, no line.
  const familyNote = document.createElement("p");
  familyNote.id = "card-family-note";
  familyNote.className = "card-family-note";
  familyNote.hidden = true;

  // Actions footer: Print and Close buttons (kept in view while the steps scroll, never printed)
  const actions = document.createElement("footer");
  actions.className = "card-actions";

  const printBtn = document.createElement("button");
  printBtn.id = "card-print-btn";
  printBtn.type = "button";
  printBtn.className = "btn btn-primary";
  printBtn.textContent = t("card.print");
  printBtn.addEventListener("click", () => {
    printCard();
  });

  const closeBtn = document.createElement("button");
  closeBtn.id = "card-close-btn";
  closeBtn.type = "button";
  closeBtn.className = "btn btn-secondary";
  closeBtn.textContent = t("card.close");
  closeBtn.addEventListener("click", () => {
    void closeCard();
  });

  actions.append(printBtn, closeBtn);
  layout.append(header, stepsList, credits, familyNote, actions);
  container.replaceChildren(layout);

  // Apply card state (composing captioned keepsake canvas and updating text)
  const applyCard = async (card: LessonCard): Promise<void> => {
    renderGeneration += 1;
    const generation = renderGeneration;
    currentCard = card;
    if (typeof document !== "undefined") {
      document.documentElement.lang = getLocale();
      document.title = `${card.title} — ${t("card.window_title")}`;
    }

    titleEl.textContent = card.title;
    renderSteps(card.steps);
    credits.textContent = t(creditsKey(card.wordsBy));
    familyNote.textContent = card.familyNote ?? "";
    familyNote.hidden = !card.familyNote;

    layout.className = "card-layout";
    imgCreditsMuse = false;
    img.removeAttribute("src");
    img.style.display = "none";
    placeholderArt.style.display = "flex";
    credits.hidden = true;

    const resolvedUrl = card.imagePath ? await resolveCardImageUrl(card.imagePath) : "";
    if (destroyed || generation !== renderGeneration) {
      return;
    }

    if (canComposeKeepsake()) {
      const rendered = await composeCaptionedKeepsake({
        title: card.title,
        steps: card.steps,
        imageUrl: resolvedUrl,
        locale: getLocale(),
        madeWithLabel: t("card.made_with"),
        familyNote: card.familyNote ?? "",
      });
      if (destroyed || generation !== renderGeneration) {
        return;
      }
      if (rendered) {
        layout.className = "card-layout has-captioned";
        imgCreditsMuse = rendered.hasPicture;
        img.src = rendered.dataUrl;
        img.style.display = "block";
        placeholderArt.style.display = "none";
        credits.hidden = !rendered.hasPicture;
        void sendCaptionedCardOnce(card.id, rendered.dataUrl, savedIds, options.saveCaptioned);
        return;
      }
    }

    if (resolvedUrl) {
      imgCreditsMuse = true;
      img.src = resolvedUrl;
    }
  };

  void applyCard(currentCard);

  return {
    getCard(): LessonCard {
      return currentCard;
    },
    async setCard(card: LessonCard): Promise<void> {
      await applyCard(card);
    },
    handleRaw(raw: unknown): boolean {
      const parsed = parseLessonCard(raw);
      if (!parsed) {
        console.warn("[card] dropped malformed lesson-card payload");
        return false;
      }
      void applyCard(parsed);
      return true;
    },
    destroy(): void {
      destroyed = true;
      container.replaceChildren();
    },
  };
}
