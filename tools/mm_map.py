# --- scanning ----------------------------------------------------------------

RUST_TOKEN = re.compile(r'//|/\*|(?<!\w)b?r(#*)"|"|\'')
TS_TOKEN = re.compile(r'//|/\*|["\'`/]')
RUST_STRING = re.compile(r'"(?:[^"\\]|\\.)*"?', re.S)
TS_STRING = {q: re.compile(q + r'(?:[^' + q + r'\\\n]|\\.)*' + q + '?', re.S) for q in '"\''}
RUST_CHAR = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]{1,6}\}|.)|[^\\'\n])'")
REGEX_AFTER = set('(,=:[!&|?{};+-*%<>~^')
REGEX_KEYWORDS = {'return', 'typeof', 'instanceof', 'case', 'in', 'of', 'new', 'delete', 'void',
                  'throw', 'yield', 'await', 'else', 'do'}


def _blank(chars, start, end):
    for k in range(start, end):
        if chars[k] != '\n':
            chars[k] = ' '


def _literal(chars, start, end):
    """Blank a string literal's contents, raw prefix included: `r#"a"#` becomes `"     "`."""
    _blank(chars, start, end)
    chars[start] = '"'
    if end - start > 1:
        chars[end - 1] = '"'


def _inner(text, start, end, quote):
    closed = end - start > 1 and text[end - 1] == quote
    return text[start + 1:end - 1 if closed else end]


def _block_end(text, start, nested):
    depth, k = 1, start + 2
    while True:
        closing = text.find('*/', k)
        if closing < 0:
            return len(text)
        opening = text.find('/*', k, closing) if nested else -1
        if opening >= 0:
            depth, k = depth + 1, opening + 2
        else:
            depth, k = depth - 1, closing + 2
            if depth == 0:
                return k


def _template_end(text, start):
    """End of the template literal opening at `start`, past its `${...}` holes."""
    k, n = start + 1, len(text)
    while k < n:
        c = text[k]
        if c == '\\':
            k += 2
        elif c == '`':
            return k + 1
        elif text.startswith('${', k):
            k = _hole_end(text, k + 2)
        else:
            k += 1
    return n


def _hole_end(text, k):
    depth, n = 1, len(text)
    while k < n:
        c = text[k]
        if c == '`':
            k = _template_end(text, k)
            continue
        if c in '"\'':
            k = TS_STRING[c].match(text, k).end()
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return k + 1
        k += 1
    return n


def _regex_allowed(code, start):
    """A `/` opens a regex after an operator, an opening bracket or a keyword, not after a value."""
    k = start - 1
    while k >= 0 and code[k].isspace():
        k -= 1
    if k < 0 or code[k] in REGEX_AFTER:
        return True
    end = k + 1
    while k >= 0 and (code[k].isalnum() or code[k] in '_$'):
        k -= 1
    return ''.join(code[k + 1:end]) in REGEX_KEYWORDS


def _regex_end(text, start):
    """End of the regex literal opening at `start`, or None when it does not close on its line."""
    k, n, in_class = start + 1, len(text), False
    while k < n:
        c = text[k]
        if c == '\n':
            return None
        if c == '\\':
            k += 2
            continue
        if in_class:
            in_class = c != ']'
        elif c == '[':
            in_class = True
        elif c == '/':
            k += 1
            while k < n and (text[k].isalnum() or text[k] == '_'):
                k += 1
            return k
        k += 1
    return None


def mask(text, lang):
    """Scan Rust ('rust') or TypeScript ('ts') source: (code, bare, strings, comments).

    `code` has the comments blanked, `bare` also the literals (a string becomes `"   "`, a char
    or regex literal spaces); both keep every offset and newline, so a regex over `bare` sees
    only real code. `strings` maps each string literal's offset to its contents (templates with
    `${}` holes are left out); `comments` lists (offset, text) in order.
    """
    code, bare = list(text), list(text)
    strings, comments = {}, []
    rust = lang == 'rust'
    token = RUST_TOKEN if rust else TS_TOKEN
    pos = 0
    while m := token.search(text, pos):
        start, kind = m.start(), m.group()
        if kind in ('//', '/*'):
            end = text.find('\n', start) if kind == '//' else _block_end(text, start, nested=rust)
            end = len(text) if end < 0 else end
            comments.append((start, text[start:end]))
            _blank(code, start, end)
            _blank(bare, start, end)
        elif kind == "'" and rust:
            char = RUST_CHAR.match(text, start)
            end = char.end() if char else start + 1  # otherwise a lifetime or a label
            if char:
                _blank(bare, start, end)
        elif kind == '/':
            end = _regex_end(text, start) if _regex_allowed(code, start) else None
            if end is None:
                end = start + 1
            else:
                _blank(bare, start, end)
        else:
            if kind == '`':
                end = _template_end(text, start)
                value = _inner(text, start, end, '`')
                value = None if '${' in value else value
            elif rust and kind != '"':
                hashes = m.group(1)
                close = text.find('"' + hashes, m.end())
                end = len(text) if close < 0 else close + 1 + len(hashes)
                value = text[m.end():len(text) if close < 0 else close]
            else:
                end = (RUST_STRING if rust else TS_STRING[kind]).match(text, start).end()
                value = _inner(text, start, end, kind)
            if value is not None:
                strings[start] = value
            _literal(bare, start, end)
        pos = end
    return ''.join(code), ''.join(bare), strings, comments


CFG_TEST = re.compile(r'#\[\s*cfg\s*\(\s*test\s*\)\s*\]')
ATTRIBUTE = re.compile(r'\s*#!?\[[^\]]*\]')


def _item_end(bare, k):
    """End of the Rust item, block or statement starting at `k` (or of its enclosing block)."""
    depth = 0
    for j in range(k, len(bare)):
        c = bare[j]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth < 0:
                return j
            if depth == 0 and c == '}':
                return j + 1
        elif c == ';' and depth == 0:
            return j + 1
    return len(bare)


def _test_spans(bare):
    """Merged offset ranges of `#[cfg(test)]` code: test modules, test-only helpers, imports."""
    spans = []
    for m in CFG_TEST.finditer(bare):
        k = m.end()
        while attribute := ATTRIBUTE.match(bare, k):
            k = attribute.end()
        spans.append((m.start(), _item_end(bare, k)))
    merged = []
    for start, end in sorted(spans):
        if merged and start <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


class Source:
    """One Rust or TypeScript file, scanned once."""

    def __init__(self, rel, text, lang):
        self.rel, self.lang = rel, lang
        self.text = text
        self.code, self.bare, self.strings, self.comments = mask(text, lang)
        self._lines = [0] + [m.end() for m in re.finditer(r'\n', text)]
        self._tests = _test_spans(self.bare) if lang == 'rust' else []

    def line(self, offset):
        return bisect.bisect_right(self._lines, offset)

    def in_test(self, offset):
        k = bisect.bisect_right(self._tests, (offset, float('inf'))) - 1
        return k >= 0 and offset < self._tests[k][1]


class Project:
    """The files under `root`, each read and scanned at most once."""

    def __init__(self, root):
        self.root = Path(root)
        self._sources, self._trees = {}, {}

    def files(self, *patterns):
        found = set()
        for pattern in patterns:
            found.update(p.relative_to(self.root).as_posix() for p in self.root.glob(pattern)
                         if p.is_file() and not is_secret(p.name))
        return sorted(found)

    def text(self, rel):
        if is_secret(Path(rel).name):
            raise ValueError('refusing to read a secrets file')
        return (self.root / rel).read_text(encoding='utf-8-sig', errors='replace')

    def source(self, rel):
        if rel not in self._sources:
            self._sources[rel] = Source(rel, self.text(rel), 'rust' if rel.endswith('.rs') else 'ts')
        return self._sources[rel]

    def tree(self, rel):
        """The module's `ast`, or None when it does not parse."""
        if rel not in self._trees:
            with warnings.catch_warnings():
                warnings.simplefilter('ignore')
                try:
                    self._trees[rel] = ast.parse(self.text(rel))
                except (SyntaxError, ValueError):
                    self._trees[rel] = None
        return self._trees[rel]

    def literals(self, files):
        """String literal contents -> [(path, line)] over the files, Rust test code left out."""
        index = {}
        for rel in files:
            src = self.source(rel)
            for offset, value in src.strings.items():
                if not src.in_test(offset):
                    index.setdefault(value, []).append((rel, src.line(offset)))
        return index


# --- part 1: files, purposes, public items -------------------------------------

SENTENCE = re.compile(r'(.+?[.!?])(?=\s+[A-Z`("\[]|$)')
RUST_ITEM = re.compile(
    r'^[ \t]*pub(?:\s*\([^)]*\))?\s+(?:(?:const|async|unsafe|extern(?:\s+"[^"]*")?)\s+)*'
    r'(?:fn|struct|enum|trait|const|static|type|mod)\s+([A-Za-z_]\w*)', re.M)
TS_EXPORT = re.compile(
    # At a line start or after a statement on the same line (literals are blanked in `bare`).
    r'(?:^|;)[ \t]*export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?'
    r'(?:function\s*\*?|class|const|let|var|type|interface|enum)\s+([A-Za-z_$][\w$]*)', re.M)
INNER_ATTRIBUTES = re.compile(r'(?:\s*#!\[[^\]]*\])*\s*')
IMPORTS = re.compile(r'(?:\s*import\b[^;]*;)*\s*')
DIRECTIVE = re.compile(r'//\s*(?:@ts-|eslint|prettier|#region)|/\*\s*(?:eslint|prettier|global\b)|///\s*<reference')


def summary(text):
    """The first sentence of the first paragraph, on one line."""
    paragraph = []
    for line in text.strip().splitlines():
        if not line.strip():
            break
        paragraph.append(line.strip())
    joined = ' '.join(paragraph)
    m = SENTENCE.match(joined)
    sentence = m.group(1) if m else joined
    if len(sentence) > SUMMARY_CHARS:
        sentence = sentence[:SUMMARY_CHARS].rsplit(' ', 1)[0] + ' …'
    return sentence


def _comment_lines(body):
    """A comment's lines without the comment markers."""
    if body.startswith('/*'):
        inner = body[3:] if body.startswith(('/**', '/*!')) else body[2:]
        inner = inner[:-2] if inner.endswith('*/') else inner
        return [re.sub(r'^\s*\*?\s?', '', line) for line in inner.splitlines()]
    return [re.sub(r'^//[/!]?\s?', '', body)]


def _rust_purpose(src):
    lines, pos = [], 0
    for start, body in src.comments:
        if INNER_ATTRIBUTES.fullmatch(src.code, pos, start) is None:
            break
        if body.startswith(('//!', '/*!')):
            lines += _comment_lines(body)
        elif lines:
            break
        pos = start + len(body)
    return summary('\n'.join(lines))


def _ts_purpose(src):
    lines, pos = [], 0
    for start, body in src.comments:
        gap = src.code[pos:start]
        if lines:
            # Line comments on the lines right below continue the block.
            if body.startswith('//') and gap.count('\n') == 1 and not gap.strip():
                lines += _comment_lines(body)
                pos = start + len(body)
                continue
            break
        if IMPORTS.fullmatch(gap) is None:
            break
        pos = start + len(body)
        if DIRECTIVE.match(body):
            continue
        lines = _comment_lines(body)
        if body.startswith('/*'):
            break
    return summary('\n'.join(lines))


def _rust_items(src):
    items, depth, pos = [], 0, 0
    for m in RUST_ITEM.finditer(src.bare):
        segment = src.bare[pos:m.start()]
        depth += segment.count('{') - segment.count('}')
        pos = m.start()
        if depth == 0 and not src.in_test(m.start()):
            items.append((m.group(1), src.line(m.start(1))))
    methods = {}
    for block in re.finditer(r'\bimpl\s*(?:<[^{}]*?>\s*)?([\w:]+)(?:\s*<[^{}]*>)?\s*(?:where\s+[^{}]+)?\{', src.bare):
        if src.in_test(block.start()):
            continue
        end = _item_end(src.bare, block.end() - 1)
        for m in RUST_ITEM.finditer(src.bare, block.end(), end):
            gap = src.bare[block.end():m.start()]
            if gap.count('{') != gap.count('}') or not re.search(r'\bfn\s+$', m.group()[:m.start(1) - m.start()]):
                continue
            if not src.in_test(m.start()):
                methods.setdefault(block.group(1), []).append((m.group(1), src.line(m.start(1))))
    for name, entries in methods.items():
        items += [(f'{name}::{method}', line) for method, line in entries[:12]]
        if len(entries) > 12:
            items.append((f'{name}::+{len(entries) - 12}', entries[12][1]))
    for m in re.finditer(r'\bpub\s+use\s+([^;]+);', src.bare):
        gap = src.bare[:m.start()]
        if gap.count('{') != gap.count('}') or src.in_test(m.start()):
            continue
        # Leaf names (including aliases) of a possibly nested use tree.
        for leaf in re.finditer(r'(\w+|\*)(?:\s+as\s+(\w+))?\s*(?=[,}]|$)', m.group(1)):
            items.append(((leaf.group(2) or leaf.group(1)) + '^', src.line(m.start())))
    return sorted(items, key=lambda item: item[1])


def _item_doc(src, line, marker):
    """Doc comment directly before the first item, allowing Rust attributes."""
    offset = src._lines[line - 1]
    comments = [(start, body) for start, body in src.comments if start < offset]
    lines, end = [], offset
    for start, body in reversed(comments):
        gap = src.code[start + len(body):end]
        if not body.startswith(marker) or re.sub(r'#\[[^\]]*\]', '', gap).strip():
            break
        lines = _comment_lines(body) + lines
        end = start
    return summary('\n'.join(lines))


def _ts_items(src):
    items = [(m.group(1), src.line(m.start(1))) for m in TS_EXPORT.finditer(src.bare)]
    for m in re.finditer(r'\bexport\s*(?:\{([^}]+)\}|(\*)(?:\s+as\s+(\w+))?)', src.bare):
        if m.group(1):
            for entry in m.group(1).split(','):
                names = re.findall(r'[\w$]+', entry)
                if names:
                    items.append((names[-1] + '^', src.line(m.start())))
        else:
            items.append(((m.group(3) or '*') + '^', src.line(m.start())))
    if not re.search(r'\bexport\b', src.bare):
        for m in re.finditer(r'\b(?:async\s+)?function\s+([\w$]+)\s*\(', src.bare):
            gap = src.bare[:m.start()]
            if gap.count('{') == gap.count('}'):
                items.append((m.group(1) + '·', src.line(m.start(1))))
        items = items[:10]
    return sorted(items, key=lambda item: item[1])


def outline(project, rel, lang):
    """(purpose, [(public item, line)]) of one source file."""
    if lang == 'python':
        tree = project.tree(rel)
        if tree is None:
            return 'does not parse', []
        public = [node for node in tree.body
                 if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                 and not node.name.startswith('_')]
        nodes = {node.lineno: node for node in public}
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and any(
                    isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute)
                    and isinstance(d.func.value, ast.Name) and d.func.value.id in ('app', 'router')
                    and d.func.attr in ROUTE_METHODS for d in node.decorator_list):
                nodes[node.lineno] = node
        items = [(node.name, line) for line, node in sorted(nodes.items())]
        doc = ast.get_docstring(tree) or (ast.get_docstring(public[0]) if public else '')
        return summary(doc or ''), items
    src = project.source(rel)
    if lang == 'rust':
        items = _rust_items(src)
        return _rust_purpose(src) or (_item_doc(src, items[0][1], '///') if items else ''), items
    items = _ts_items(src)
    return _ts_purpose(src) or (_item_doc(src, items[0][1], '/**') if items else ''), items


def _chunks(tokens, size):
    return [tokens[k:k + size] for k in range(0, len(tokens), size)]


def _item_token(name, line):
    marker = name[-1] if name.endswith(('^', '·')) else ''
    return f'{name[:-1] if marker else name}:{line}{marker}'


def _sources_part(project, sources):
    out = []
    counts = _test_counts(project, [rel for _, rel, lang in sources if lang == 'rust'])
    _block(out, '## Source files', 'Each file with its purpose, then its public items: Rust `pub` (and `pub(crate)`) '
           'items and inherent methods, TypeScript exports, Python public definitions and route handlers. '
           '`^`: re-export; `·`: module-local TS function (first 10); methods: first 12 per type, then +N. Test code is excluded.')
    area = None
    for file_area, rel, lang in sources:
        if file_area != area:
            area = file_area
            _block(out, f'### {area}')
        purpose, items = outline(project, rel, lang)
        out.append(f'- {rel} — {purpose}' if purpose else f'- {rel}')
        out += ['  ' + ' '.join(chunk) for chunk in _chunks([_item_token(name, line) for name, line in items], ITEMS_PER_LINE)]
        matches = _matching_tests(rel, counts)
        if matches:
            out.append('  tests: ' + ', '.join(f'{path} ({counts[path]})' for path in matches))
        if lang == 'rust' and counts.get(rel) and any(
                re.search(r'\bmod\s+\w+\s*\{', project.source(rel).bare[start:end])
                for start, end in project.source(rel)._tests):
            out.append(f'  inline tests ({counts[rel]})')
    return out


