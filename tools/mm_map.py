# --- scanning ----------------------------------------------------------------

RUST_TOKEN = re.compile(r'//|/\*|(?<!\w)b?r(#*)"|"|\'')
TS_TOKEN = re.compile(r'//|/\*|["\'`/]')
RUST_STRING = re.compile(r'"(?:[^"\\]|\\.)*"?', re.S)
TS_STRING = {q: re.compile(q + r'(?:[^' + q + r'\\\n]|\\.)*' + q + '?', re.S) for q in '"\''}
RUST_CHAR = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]{1,6}\}|.)|[^\\'\n])'")
REGEX_AFTER = set('(,=:[!&|?{};+-*%<>~^')
REGEX_KEYWORDS = {'return', 'typeof', 'instanceof', 'case', 'in', 'of', 'new', 'delete', 'void',
                  'throw', 'yield', 'await', 'else', 'do'}


def _blank(chars, start, end):
    for k in range(start, end):
        if chars[k] != '\n':
            chars[k] = ' '


def _literal(chars, start, end):
    """Blank a string literal's contents, raw prefix included: `r#"a"#` becomes `"     "`."""
    _blank(chars, start, end)
    chars[start] = '"'
    if end - start > 1:
        chars[end - 1] = '"'


def _inner(text, start, end, quote):
    closed = end - start > 1 and text[end - 1] == quote
    return text[start + 1:end - 1 if closed else end]


def _block_end(text, start, nested):
    depth, k = 1, start + 2
    while True:
        closing = text.find('*/', k)
        if closing < 0:
            return len(text)
        opening = text.find('/*', k, closing) if nested else -1
        if opening >= 0:
            depth, k = depth + 1, opening + 2
        else:
            depth, k = depth - 1, closing + 2
            if depth == 0:
                return k


def _template_end(text, start):
    """End of the template literal opening at `start`, past its `${...}` holes."""
    k, n = start + 1, len(text)
    while k < n:
        c = text[k]
        if c == '\\':
            k += 2
        elif c == '`':
            return k + 1
        elif text.startswith('${', k):
            k = _hole_end(text, k + 2)
        else:
            k += 1
    return n


def _hole_end(text, k):
    depth, n = 1, len(text)
    while k < n:
        c = text[k]
        if c == '`':
            k = _template_end(text, k)
            continue
        if c in '"\'':
            k = TS_STRING[c].match(text, k).end()
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return k + 1
        k += 1
    return n


def _regex_allowed(code, start):
    """A `/` opens a regex after an operator, an opening bracket or a keyword, not after a value."""
    k = start - 1
    while k >= 0 and code[k].isspace():
        k -= 1
    if k < 0 or code[k] in REGEX_AFTER:
        return True
    end = k + 1
    while k >= 0 and (code[k].isalnum() or code[k] in '_$'):
        k -= 1
    return ''.join(code[k + 1:end]) in REGEX_KEYWORDS


def _regex_end(text, start):
    """End of the regex literal opening at `start`, or None when it does not close on its line."""
    k, n, in_class = start + 1, len(text), False
    while k < n:
        c = text[k]
        if c == '\n':
            return None
        if c == '\\':
            k += 2
            continue
        if in_class:
            in_class = c != ']'
        elif c == '[':
            in_class = True
        elif c == '/':
            k += 1
            while k < n and (text[k].isalnum() or text[k] == '_'):
                k += 1
            return k
        k += 1
    return None


def mask(text, lang):
    """Scan Rust ('rust') or TypeScript ('ts') source: (code, bare, strings, comments).

    `code` has the comments blanked, `bare` also the literals (a string becomes `"   "`, a char
    or regex literal spaces); both keep every offset and newline, so a regex over `bare` sees
    only real code. `strings` maps each string literal's offset to its contents (templates with
    `${}` holes are left out); `comments` lists (offset, text) in order.
    """
    code, bare = list(text), list(text)
    strings, comments = {}, []
    rust = lang == 'rust'
    token = RUST_TOKEN if rust else TS_TOKEN
    pos = 0
    while m := token.search(text, pos):
        start, kind = m.start(), m.group()
        if kind in ('//', '/*'):
            end = text.find('\n', start) if kind == '//' else _block_end(text, start, nested=rust)
            end = len(text) if end < 0 else end
            comments.append((start, text[start:end]))
            _blank(code, start, end)
            _blank(bare, start, end)
        elif kind == "'" and rust:
            char = RUST_CHAR.match(text, start)
            end = char.end() if char else start + 1  # otherwise a lifetime or a label
            if char:
                _blank(bare, start, end)
        elif kind == '/':
            end = _regex_end(text, start) if _regex_allowed(code, start) else None
            if end is None:
                end = start + 1
            else:
                _blank(bare, start, end)
        else:
            if kind == '`':
                end = _template_end(text, start)
                value = _inner(text, start, end, '`')
                value = None if '${' in value else value
            elif rust and kind != '"':
                hashes = m.group(1)
                close = text.find('"' + hashes, m.end())
                end = len(text) if close < 0 else close + 1 + len(hashes)
                value = text[m.end():len(text) if close < 0 else close]
            else:
                end = (RUST_STRING if rust else TS_STRING[kind]).match(text, start).end()
                value = _inner(text, start, end, kind)
            if value is not None:
                strings[start] = value
            _literal(bare, start, end)
        pos = end
    return ''.join(code), ''.join(bare), strings, comments


CFG_TEST = re.compile(r'#\[\s*cfg\s*\(\s*test\s*\)\s*\]')
ATTRIBUTE = re.compile(r'\s*#!?\[[^\]]*\]')


def _item_end(bare, k):
    """End of the Rust item, block or statement starting at `k` (or of its enclosing block)."""
    depth = 0
    for j in range(k, len(bare)):
        c = bare[j]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth < 0:
                return j
            if depth == 0 and c == '}':
                return j + 1
        elif c == ';' and depth == 0:
            return j + 1
    return len(bare)


def _test_spans(bare):
    """Merged offset ranges of `#[cfg(test)]` code: test modules, test-only helpers, imports."""
    spans = []
    for m in CFG_TEST.finditer(bare):
        k = m.end()
        while attribute := ATTRIBUTE.match(bare, k):
            k = attribute.end()
        spans.append((m.start(), _item_end(bare, k)))
    merged = []
    for start, end in sorted(spans):
        if merged and start <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


class Source:
    """One Rust or TypeScript file, scanned once."""

    def __init__(self, rel, text, lang):
        self.rel, self.lang = rel, lang
        self.code, self.bare, self.strings, self.comments = mask(text, lang)
        self._lines = [0] + [m.end() for m in re.finditer(r'\n', text)]
        self._tests = _test_spans(self.bare) if lang == 'rust' else []

    def line(self, offset):
        return bisect.bisect_right(self._lines, offset)

    def in_test(self, offset):
        k = bisect.bisect_right(self._tests, (offset, float('inf'))) - 1
        return k >= 0 and offset < self._tests[k][1]


class Project:
    """The files under `root`, each read and scanned at most once."""

    def __init__(self, root):
        self.root = Path(root)
        self._sources, self._trees = {}, {}

    def files(self, *patterns):
        found = set()
        for pattern in patterns:
            found.update(p.relative_to(self.root).as_posix() for p in self.root.glob(pattern) if p.is_file())
        return sorted(found)

    def text(self, rel):
        return (self.root / rel).read_text(encoding='utf-8-sig', errors='replace')

    def source(self, rel):
        if rel not in self._sources:
            self._sources[rel] = Source(rel, self.text(rel), 'rust' if rel.endswith('.rs') else 'ts')
        return self._sources[rel]

    def tree(self, rel):
        """The module's `ast`, or None when it does not parse."""
        if rel not in self._trees:
            with warnings.catch_warnings():
                warnings.simplefilter('ignore')
                try:
                    self._trees[rel] = ast.parse(self.text(rel))
                except (SyntaxError, ValueError):
                    self._trees[rel] = None
        return self._trees[rel]

    def literals(self, files):
        """String literal contents -> [(path, line)] over the files, Rust test code left out."""
        index = {}
        for rel in files:
            src = self.source(rel)
            for offset, value in src.strings.items():
                if not src.in_test(offset):
                    index.setdefault(value, []).append((rel, src.line(offset)))
        return index


# --- part 1: files, purposes, public items -------------------------------------

SENTENCE = re.compile(r'(.+?[.!?])(?=\s+[A-Z`("\[]|$)')
RUST_ITEM = re.compile(
    r'^[ \t]*pub(?:\s*\([^)]*\))?\s+(?:(?:const|async|unsafe|extern(?:\s+"[^"]*")?)\s+)*'
    r'(?:fn|struct|enum|trait|const|static|type|mod)\s+([A-Za-z_]\w*)', re.M)
TS_EXPORT = re.compile(
    # At a line start or after a statement on the same line (literals are blanked in `bare`).
    r'(?:^|;)[ \t]*export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?'
    r'(?:function\s*\*?|class|const|let|var|type|interface|enum)\s+([A-Za-z_$][\w$]*)', re.M)
INNER_ATTRIBUTES = re.compile(r'(?:\s*#!\[[^\]]*\])*\s*')
IMPORTS = re.compile(r'(?:\s*import\b[^;]*;)*\s*')
DIRECTIVE = re.compile(r'//\s*(?:@ts-|eslint|prettier|#region)|/\*\s*(?:eslint|prettier|global\b)|///\s*<reference')


def summary(text):
    """The first sentence of the first paragraph, on one line."""
    paragraph = []
    for line in text.strip().splitlines():
        if not line.strip():
            break
        paragraph.append(line.strip())
    joined = ' '.join(paragraph)
    m = SENTENCE.match(joined)
    sentence = m.group(1) if m else joined
    if len(sentence) > SUMMARY_CHARS:
        sentence = sentence[:SUMMARY_CHARS].rsplit(' ', 1)[0] + ' …'
    return sentence


def _comment_lines(body):
    """A comment's lines without the comment markers."""
    if body.startswith('/*'):
        inner = body[3:] if body.startswith(('/**', '/*!')) else body[2:]
        inner = inner[:-2] if inner.endswith('*/') else inner
        return [re.sub(r'^\s*\*?\s?', '', line) for line in inner.splitlines()]
    return [re.sub(r'^//[/!]?\s?', '', body)]


def _rust_purpose(src):
    lines, pos = [], 0
    for start, body in src.comments:
        if INNER_ATTRIBUTES.fullmatch(src.code, pos, start) is None:
            break
        if body.startswith(('//!', '/*!')):
            lines += _comment_lines(body)
        elif lines:
            break
        pos = start + len(body)
    return summary('\n'.join(lines))


def _ts_purpose(src):
    lines, pos = [], 0
    for start, body in src.comments:
        gap = src.code[pos:start]
        if lines:
            # Line comments on the lines right below continue the block.
            if body.startswith('//') and gap.count('\n') == 1 and not gap.strip():
                lines += _comment_lines(body)
                pos = start + len(body)
                continue
            break
        if IMPORTS.fullmatch(gap) is None:
            break
        pos = start + len(body)
        if DIRECTIVE.match(body):
            continue
        lines = _comment_lines(body)
        if body.startswith('/*'):
            break
    return summary('\n'.join(lines))


def _rust_items(src):
    items, depth, pos = [], 0, 0
    for m in RUST_ITEM.finditer(src.bare):
        segment = src.bare[pos:m.start()]
        depth += segment.count('{') - segment.count('}')
        pos = m.start()
        if depth == 0 and not src.in_test(m.start()):
            items.append((m.group(1), src.line(m.start(1))))
    return items


def outline(project, rel, lang):
    """(purpose, [(public item, line)]) of one source file."""
    if lang == 'python':
        tree = project.tree(rel)
        if tree is None:
            return 'does not parse', []
        items = [(node.name, node.lineno) for node in tree.body
                 if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                 and not node.name.startswith('_')]
        return summary(ast.get_docstring(tree) or ''), items
    src = project.source(rel)
    if lang == 'rust':
        return _rust_purpose(src), _rust_items(src)
    return _ts_purpose(src), [(m.group(1), src.line(m.start(1))) for m in TS_EXPORT.finditer(src.bare)]


def _chunks(tokens, size):
    return [tokens[k:k + size] for k in range(0, len(tokens), size)]


def _sources_part(project, sources):
    out = []
    _block(out, '## Source files', 'Each file with its purpose, then its public items: Rust `pub` (and `pub(crate)`) '
           'items outside impl blocks and test code, TypeScript exports, Python top-level `def` and `class`.')
    area = None
    for file_area, rel, lang in sources:
        if file_area != area:
            area = file_area
            _block(out, f'### {area}')
        purpose, items = outline(project, rel, lang)
        out.append(f'- {rel} — {purpose}' if purpose else f'- {rel}')
        out += ['  ' + ' '.join(chunk) for chunk in _chunks([f'{name}:{line}' for name, line in items], ITEMS_PER_LINE)]
    return out


# --- part 2: cross-language links --------------------------------------------

TAURI_COMMAND = re.compile(
    r'#\[\s*tauri\s*::\s*command\b[^\]]*\]\s*(?:#\[[^\]]*\]\s*)*'
    r'(?:pub(?:\s*\([^)]*\))?\s+)?(?:async\s+)?(?:unsafe\s+)?fn\s+([A-Za-z_]\w*)')
RUST_EVENT_CALL = re.compile(r'\.(emit|emit_to|emit_filter|listen|listen_any|once|once_any)\s*(?:::\s*<[^()]*?>\s*)?\(')
TS_EVENT_CALL = re.compile(r'(?<![\w$])(emit|emitTo|listen|once)\s*(?:<[^()]*?>\s*)?\(')
EVENT_ARG = {'emit_to': 1, 'emitTo': 1}
EVENT_KINDS = ('rs emit', 'ts emit', 'rs listen', 'ts listen', 'const')
RUST_STR_CONST = re.compile(r'\bconst\s+([A-Z][A-Z0-9_]*)\s*:\s*&\s*(?:\'static\s+)?str\s*=\s*(?=")')
TS_STR_CONST = re.compile(r'\bconst\s+([A-Z][A-Z0-9_]*)\s*(?::\s*string\s*)?=\s*(?=")')
CONST_END = re.compile(r'\s*(?:as\s+const\b\s*)?(?:;|\n)')
LITERAL = re.compile(r'"[^"]*"')
IDENT_PATH = re.compile(r'[A-Za-z_$][\w$]*(?:(?:::|\.)[A-Za-z_$][\w$]*)*')
ROUTE_METHODS = {'get': 'GET', 'post': 'POST', 'put': 'PUT', 'patch': 'PATCH', 'delete': 'DELETE',
                 'websocket': 'WS', 'api_route': 'ANY', 'route': 'ANY'}
CALL_IMPL = re.compile(r'\bimpl\s+' + CALL_KIND + r'\s*\{')
CALL_ARM = re.compile(r'\b(?:Self|' + CALL_KIND + r')\s*::\s*(\w+)\s*=>\s*(?=")')
CALL_USE = re.compile(r'\b' + CALL_KIND + r'\s*::\s*(\w+)\b')


def _sites(sites):
    """[(path, line)] -> 'a.rs:1,5, b.ts:3': sorted, one entry per file."""
    by_path = {}
    for path, line in sorted(set(sites)):
        by_path.setdefault(path, []).append(str(line))
    return ', '.join(f'{path}:{",".join(lines)}' for path, lines in by_path.items())


def _call_args(bare, paren):
    """Offset ranges of the top-level arguments of the call whose `(` is at `paren`."""
    spans, depth, start = [], 0, paren + 1
    for k in range(paren, len(bare)):
        c = bare[k]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                if bare[start:k].strip():
                    spans.append((start, k))
                return spans
        elif c == ',' and depth == 1:
            spans.append((start, k))
            start = k + 1
    return spans


def _module_of(rel):
    path = PurePosixPath(rel)
    return path.parent.name if path.stem in ('mod', 'lib', 'main', 'index') else path.stem


def _consts(project, files):
    """UPPER_CASE string constants: name -> [(value, path, line)]."""
    table = {}
    for rel in files:
        src = project.source(rel)
        for m in (RUST_STR_CONST if src.lang == 'rust' else TS_STR_CONST).finditer(src.bare):
            quote = m.end()
            close = src.bare.find('"', quote + 1)
            if (quote in src.strings and close > 0 and CONST_END.match(src.bare, close + 1)
                    and not src.in_test(m.start())):
                table.setdefault(m.group(1), []).append((src.strings[quote], rel, src.line(m.start(1))))
    return table


def _resolve(table, token, rel):
    """(value, definition sites) of a constant named by `token` in `rel`; (None, []) if unknown or ambiguous."""
    parts = re.split(r'::|\.', token)
    found = table.get(parts[-1], [])
    if len(parts) > 1:
        first = [f for f in found if _module_of(f[1]) == parts[-2]]
    else:
        first = [f for f in found if f[1] == rel]
    for candidates in (first, found):
        values = {value for value, _, _ in candidates}
        if len(values) == 1:
            return values.pop(), [(path, line) for _, path, line in candidates]
        if values:
            break
    return None, []


def _arg_value(src, span, table):
    start, end = span
    raw = src.bare[start:end]
    token = raw.strip()
    if LITERAL.fullmatch(token):
        value = src.strings.get(start + len(raw) - len(raw.lstrip()))
        return value, []
    if IDENT_PATH.fullmatch(token):
        return _resolve(table, token, src.rel)
    return None, []


def _commands(project, rust, ts_literals):
    commands = []
    for rel in rust:
        src = project.source(rel)
        commands += [(m.group(1), rel, src.line(m.start(1))) for m in TAURI_COMMAND.finditer(src.bare)
                     if not src.in_test(m.start())]
    if not commands:
        return []
    out = []
    _block(out, '### Tauri commands', 'Rust `#[tauri::command]` <- TypeScript string literals naming it '
           '(`invoke("name")`, command constants, menu items).')
    for name, rel, line in sorted(commands):
        callers = ts_literals.get(name)
        out.append(f'- `{name}` {rel}:{line} <- {_sites(callers) if callers else "no TypeScript caller"}')
    return out


def _event_sites(project, rust, ts):
    """Event names -> kinds -> sites, shared with the contract checker."""
    events = {}
    for files, pattern, side in ((rust, RUST_EVENT_CALL, 'rs'), (ts, TS_EVENT_CALL, 'ts')):
        table = _consts(project, files)
        for rel in files:
            src = project.source(rel)
            for m in pattern.finditer(src.bare):
                args = _call_args(src.bare, m.end() - 1)
                index = EVENT_ARG.get(m.group(1), 0)
                if src.in_test(m.start()) or index >= len(args):
                    continue
                value, defined = _arg_value(src, args[index], table)
                if value is None:
                    continue
                sites = events.setdefault(value, {})
                kind = f'{side} emit' if m.group(1).startswith('emit') else f'{side} listen'
                sites.setdefault(kind, []).append((rel, src.line(m.start(1))))
                sites.setdefault('const', []).extend(defined)
    return events


def _events(project, rust, ts):
    events = _event_sites(project, rust, ts)
    if not events:
        return []
    out = []
    _block(out, '### Events', 'Tauri events by name: `emit`/`emit_to` and `listen`/`once` calls in Rust (rs) and '
           'TypeScript (ts), with a string literal or a constant; `const`: where that constant is defined.')
    for name in sorted(events):
        parts = [f'{kind} {_sites(events[name][kind])}' for kind in EVENT_KINDS if events[name].get(kind)]
        out.append(f'- `{name}`: ' + '; '.join(parts))
    return out


def _route_pattern(path):
    pieces = re.split(r'(\{[^{}]*\})', path)
    body = ''.join(r'[^/?#"]+' if piece.startswith('{') else re.escape(piece) for piece in pieces)
    return re.compile(r'(?:^|(?<=[\w}\].:]))' + body + r'(?=$|[?#])')


def _routes(project, server, rust_literals):
    routes = []
    for rel in server:
        tree = project.tree(rel)
        for node in ast.walk(tree) if tree else ():
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute)
                        and deco.func.attr in ROUTE_METHODS and deco.args
                        and isinstance(deco.args[0], ast.Constant) and isinstance(deco.args[0].value, str)
                        and deco.args[0].value.startswith('/')):
                    routes.append((deco.args[0].value, ROUTE_METHODS[deco.func.attr], rel, deco.lineno))
    if not routes:
        return []
    out = []
    _block(out, '### Proxy routes', 'Server route decorators <- Rust string literals (URLs, `format!` templates) '
           'that end in the route.')
    for path, method, rel, line in sorted(routes):
        pattern = _route_pattern(path)
        callers = [site for value, sites in rust_literals.items() if pattern.search(value) for site in sites]
        out.append(f'- {method} {path} {rel}:{line} <- {_sites(callers) if callers else "no Rust caller"}')
    return out


def _call_kinds(project, rust, server):
    header, server_values = [], {}
    for rel in server:
        tree = project.tree(rel)
        for node in ast.walk(tree) if tree else ():
            if isinstance(node, ast.ClassDef) and node.name == CALL_KIND:
                for stmt in node.body:
                    if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1
                            and isinstance(stmt.targets[0], ast.Name)
                            and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str)):
                        server_values.setdefault(stmt.value.value, []).append((rel, stmt.lineno))
            elif isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.lower() == CALL_HEADER:
                header.append(('py', rel, node.lineno))
    arms, variants, uses = {}, {}, {}
    for rel in rust:
        src = project.source(rel)
        header += [('rs', rel, src.line(offset)) for offset, value in src.strings.items()
                   if value.lower() == CALL_HEADER and not src.in_test(offset)]
        blocks = [(m.start(), _item_end(src.bare, m.end() - 1)) for m in CALL_IMPL.finditer(src.bare)]
        for start, end in blocks:
            for arm in CALL_ARM.finditer(src.bare, start, end):
                value = src.strings.get(arm.end())
                if value is not None:
                    arms.setdefault(value, []).append((rel, src.line(arm.start())))
                    variants.setdefault(arm.group(1), set()).add(value)
        for m in CALL_USE.finditer(src.bare):
            if not src.in_test(m.start()) and not any(start <= m.start() < end for start, end in blocks):
                uses.setdefault(m.group(1), []).append((rel, src.line(m.start())))
    if not header and not server_values and not arms:
        return []
    out = []
    _block(out, '### X-MetaMate-Call', f'The header names the kind of a proxy call: server `{CALL_KIND}` value (py) '
           f'and the Rust `{CALL_KIND}` variant that sends it (rs), then the Rust calls that use it.')
    if header:
        parts = [f'{side} {_sites([(rel, line) for s, rel, line in header if s == side])}'
                 for side in ('rs', 'py') if any(s == side for s, _, _ in header)]
        out.append('- header: ' + '; '.join(parts))
    for value in sorted(set(server_values) | set(arms)):
        sent = [site for variant, values in variants.items() if value in values for site in uses.get(variant, [])]
        parts = [f'{label} {_sites(sites)}' for label, sites in
                 (('py', server_values.get(value)), ('rs', arms.get(value)), ('used', sent)) if sites]
        out.append(f'- `{value}`: ' + '; '.join(parts))
    return out


def _locale_keys(project, rust_literals, ts_literals):
    path = project.root / LOCALE
    try:
        keys = sorted(json.loads(path.read_text(encoding='utf-8-sig')))
    except (OSError, ValueError, TypeError):
        return []
    out, unused = [], []
    _block(out, '### Locale keys', f'Keys of {LOCALE} found as string literals in Rust (rs: crates, src-tauri) and '
           'TypeScript (ts: `t("key")`, key tables).')
    for key in keys:
        parts = [f'{side} {_sites(index[key])}' for side, index in (('rs', rust_literals), ('ts', ts_literals))
                 if key in index]
        if parts:
            out.append(f'- `{key}`: ' + '; '.join(parts))
        else:
            unused.append(f'`{key}`')
    if unused:
        out.append('- no literal use (built at run time, or unused):')
        out += ['  ' + ' '.join(chunk) for chunk in _chunks(unused, ITEMS_PER_LINE)]
    return out


# --- part 3: tests -------------------------------------------------------------

RUST_TEST = re.compile(r'#\[\s*(?:\w+\s*::\s*)*test\b')
TS_TEST = re.compile(r'^[ \t]*(?:test|it)(?:\.(?:only|skip|todo))?\s*\(', re.M)


def _test_area(rel):
    parts = rel.split('/')
    return '/'.join(parts[:2]) if parts[0] == 'crates' else parts[0]


def _tests_part(project, rust):
    counts = {}
    for rel in project.files(*RUST_TESTS) + rust:
        counts[rel] = len(RUST_TEST.findall(project.source(rel).bare))
    for rel in project.files(*TS_TESTS):
        counts[rel] = len(TS_TEST.findall(project.source(rel).bare))
    for rel in project.files(*PY_TESTS):
        tree = project.tree(rel)
        counts[rel] = sum(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith('test')
                          for node in ast.walk(tree)) if tree else 0
    areas = {}
    for rel, count in counts.items():
        if count:
            areas.setdefault(_test_area(rel), []).append((rel, count))
    out = []
    _block(out, '## Tests', 'Per area: the test files and the source files with inline tests, with their number of '
           'tests (Rust `#[test]`, TypeScript `test(`/`it(`, Python `test*` methods).')
    order = {name: k for k, name in enumerate(TEST_AREAS)}
    for area in sorted(areas, key=lambda name: (order.get(name.split('/')[0], len(order)), name)):
        files = sorted(areas[area])
        _block(out, f'### {area}: {sum(n for _, n in files)} tests in {len(files)} files')
        out += [f'- {rel}: {count}' for rel, count in files]
    return out


# --- render, main --------------------------------------------------------------

def _block(out, heading, intro=None):
    if out and out[-1] != '':
        out.append('')
    out += [heading, '']
    if intro:
        out += [intro, '']


def render(root=ROOT):
    """The whole docs/code-map.md for the tree at `root`."""
    project = Project(root)
    sources, seen = [], set()
    for pattern, lang, area in SOURCES:
        for rel in project.files(pattern):
            if rel not in seen and not rel.endswith('.test.ts'):
                seen.add(rel)
                sources.append((area or '/'.join(rel.split('/')[:2]), rel, lang))
    rust = [rel for _, rel, lang in sources if lang == 'rust']
    ts = [rel for _, rel, lang in sources if lang == 'ts']
    server = [rel for area, rel, _ in sources if area == 'server/metamate_proxy']
    rust_literals, ts_literals = project.literals(rust), project.literals(ts)

    out = [HEADER, '# Code map', '', INTRO]
    _extend(out, _sources_part(project, sorted(sources, key=lambda s: (_area_rank(s[0]), s[0], s[1]))))
    links = [part for part in (_commands(project, rust, ts_literals), _events(project, rust, ts),
                               _routes(project, server, rust_literals), _call_kinds(project, rust, server),
                               _locale_keys(project, rust_literals, ts_literals)) if part]
    if links:
        _block(out, '## Cross-language links')
        for part in links:
            _extend(out, part)
    _extend(out, _tests_part(project, rust))
    while out[-1] == '':
        out.pop()
    return '\n'.join(out) + '\n'


def _extend(out, part):
    if part and out[-1] != '':
        out.append('')
    out += part


def _area_rank(area):
    """Areas in the order of SOURCES; the crates sort by name."""
    for k, (pattern, _, name) in enumerate(SOURCES):
        if area == name or (name is None and area.startswith(pattern.split('/')[0] + '/')):
            return k
    return len(SOURCES)


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(prog='mm map', description='Write docs/code-map.md (see the module docstring).')
    parser.add_argument('--check', action='store_true', help='exit 1 when docs/code-map.md is stale')
    args = parser.parse_args(argv)
    root = Path(root)
    text = render(root)
    target = root / OUTPUT
    try:
        current = target.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        current = None
    if current == text:
        print(f'{OUTPUT}: up to date')
        return 0
    if args.check:
        print(f'{OUTPUT} is stale: run `mm map`')
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT} ({text.count(chr(10))} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
