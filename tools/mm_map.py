def _sites(sites):
    """[(path, line)] -> 'a.rs:1,5, b.ts:3': sorted, one entry per file."""
    by_path = {}
    for path, line in sorted(set(sites)):
        by_path.setdefault(path, []).append(str(line))
    return ', '.join(f'{path}:{",".join(lines)}' for path, lines in by_path.items())


def _call_args(bare, paren):
    """Offset ranges of the top-level arguments of the call whose `(` is at `paren`."""
    spans, depth, start = [], 0, paren + 1
    for k in range(paren, len(bare)):
        c = bare[k]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                if bare[start:k].strip():
                    spans.append((start, k))
                return spans
        elif c == ',' and depth == 1:
            spans.append((start, k))
            start = k + 1
    return spans


def _module_of(rel):
    path = PurePosixPath(rel)
    return path.parent.name if path.stem in ('mod', 'lib', 'main', 'index') else path.stem


def _consts(project, files):
    """UPPER_CASE string constants: name -> [(value, path, line)]."""
    table = {}
    for rel in files:
        src = project.source(rel)
        for m in (RUST_STR_CONST if src.lang == 'rust' else TS_STR_CONST).finditer(src.bare):
            quote = m.end()
            close = src.bare.find('"', quote + 1)
            if (quote in src.strings and close > 0 and CONST_END.match(src.bare, close + 1)
                    and not src.in_test(m.start())):
                table.setdefault(m.group(1), []).append((src.strings[quote], rel, src.line(m.start(1))))
    return table


def _resolve(table, token, rel):
    """(value, definition sites) of a constant named by `token` in `rel`; (None, []) if unknown or ambiguous."""
    parts = re.split(r'::|\.', token)
    found = table.get(parts[-1], [])
    if len(parts) > 1:
        first = [f for f in found if _module_of(f[1]) == parts[-2]]
    else:
        first = [f for f in found if f[1] == rel]
    for candidates in (first, found):
        values = {value for value, _, _ in candidates}
        if len(values) == 1:
            return values.pop(), [(path, line) for _, path, line in candidates]
        if values:
            break
    return None, []


def _arg_value(src, span, table):
    start, end = span
    raw = src.bare[start:end]
    token = raw.strip()
    if LITERAL.fullmatch(token):
        value = src.strings.get(start + len(raw) - len(raw.lstrip()))
        return value, []
    if IDENT_PATH.fullmatch(token):
        return _resolve(table, token, src.rel)
    return None, []


def _commands(project, rust, ts_literals):
    commands = []
    for rel in rust:
        src = project.source(rel)
        commands += [(m.group(1), rel, src.line(m.start(1))) for m in TAURI_COMMAND.finditer(src.bare)
                     if not src.in_test(m.start())]
    if not commands:
        return []
    out = []
    _block(out, '### Tauri commands', 'Rust `#[tauri::command]` <- TypeScript string literals naming it '
           '(`invoke("name")`, command constants, menu items).')
    for name, rel, line in sorted(commands):
        callers = ts_literals.get(name)
        out.append(f'- `{name}` {rel}:{line} <- {_sites(callers) if callers else "no TypeScript caller"}')
    return out


def _channels(project, rust, ts):
    commands = {}
    for rel in rust:
        src = project.source(rel)
        for m in TAURI_COMMAND.finditer(src.bare):
            paren = src.bare.find('(', m.end())
            args = _call_args(src.bare, paren)
            if (not src.in_test(m.start()) and args
                    and re.search(r'\bChannel\s*<', src.bare[paren:args[-1][1]])):
                commands[m.group(1)] = (rel, src.line(m.start(1)))
    if not commands:
        return []
    sites = {}
    for rel in ts:
        src = project.source(rel)
        for m in re.finditer(r'\b(?:const|let)\s+(\w+)\s*=\s*new\s+Channel\b', src.bare):
            # Follow the channel binding within the enclosing block, including async setup.
            stack = []
            for k, char in enumerate(src.bare[:m.start()]):
                if char == '{':
                    stack.append(k)
                elif char == '}' and stack:
                    stack.pop()
            end = _item_end(src.bare, stack[-1]) if stack else len(src.bare)
            for call in re.finditer(r'\binvoke\s*(?:<[^()]*>\s*)?\(', src.bare[m.end():end]):
                paren = m.end() + call.end() - 1
                args = _call_args(src.bare, paren)
                if len(args) < 2:
                    continue
                name, _ = _arg_value(src, args[0], {})
                if name in commands and re.search(r'\b' + re.escape(m.group(1)) + r'\b',
                                                  src.bare[args[1][0]:args[-1][1]]):
                    sites.setdefault(name, []).append((rel, src.line(src.bare.index('new', m.start(), m.end()))))
    out = []
    _block(out, '### Tauri Channels', 'Commands accepting `Channel<...>` <- TypeScript `new Channel` bindings passed to them.')
    for name, (rel, line) in sorted(commands.items()):
        out.append(f'- `{name}` {rel}:{line} <- {_sites(sites[name]) if name in sites else "no TypeScript Channel site"}')
    return out


def _disk_files(project, rust):
    files = {}
    for name, entries in _consts(project, rust).items():
        for value, rel, line in entries:
            if re.fullmatch(r'[^/\\\s]+\.(?:json|bin|id|txt|log|wav|tmp)', value):
                files.setdefault(value, []).append((rel, line))
    if not files:
        return []
    out = []
    _block(out, '### Files on disk', 'File names declared as Rust string constants (read or written by the app).')
    out += [f'- `{value}`: {_sites(sites)}' for value, sites in sorted(files.items())]
    return out


def _event_sites(project, rust, ts):
    """Event names -> kinds -> sites, shared with the contract checker."""
    events = {}
    for files, pattern, side in ((rust, RUST_EVENT_CALL, 'rs'), (ts, TS_EVENT_CALL, 'ts')):
        table = _consts(project, files)
        for rel in files:
            src = project.source(rel)
            for m in pattern.finditer(src.bare):
                args = _call_args(src.bare, m.end() - 1)
                index = EVENT_ARG.get(m.group(1), 0)
                if src.in_test(m.start()) or index >= len(args):
                    continue
                value, defined = _arg_value(src, args[index], table)
                if value is None:
                    continue
                sites = events.setdefault(value, {})
                kind = f'{side} emit' if m.group(1).startswith('emit') else f'{side} listen'
                sites.setdefault(kind, []).append((rel, src.line(m.start(1))))
                sites.setdefault('const', []).extend(defined)
    return events


def _events(project, rust, ts):
    events = _event_sites(project, rust, ts)
    if not events:
        return []
    out = []
    _block(out, '### Events', 'Tauri events by name: `emit`/`emit_to` and `listen`/`once` calls in Rust (rs) and '
           'TypeScript (ts), with a string literal or a constant; `const`: where that constant is defined.')
    for name in sorted(events):
        parts = [f'{kind} {_sites(events[name][kind])}' for kind in EVENT_KINDS if events[name].get(kind)]
        out.append(f'- `{name}`: ' + '; '.join(parts))
    return out


def _route_pattern(path):
    pieces = re.split(r'(\{[^{}]*\})', path)
    body = ''.join(r'[^/?#"]+' if piece.startswith('{') else re.escape(piece) for piece in pieces)
    return re.compile(r'(?:^|(?<=[\w}\].:]))' + body + r'(?=$|[?#])')


def _routes(project, server, rust_literals):
    routes = []
    for rel in server:
        tree = project.tree(rel)
        for node in ast.walk(tree) if tree else ():
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute)
                        and deco.func.attr in ROUTE_METHODS and deco.args
                        and isinstance(deco.args[0], ast.Constant) and isinstance(deco.args[0].value, str)
                        and deco.args[0].value.startswith('/')):
                    routes.append((deco.args[0].value, ROUTE_METHODS[deco.func.attr], rel, deco.lineno))
    if not routes:
        return []
    out = []
    _block(out, '### Proxy routes', 'Server route decorators <- Rust string literals (URLs, `format!` templates) '
           'that end in the route.')
    for path, method, rel, line in sorted(routes):
        pattern = _route_pattern(path)
        callers = [site for value, sites in rust_literals.items() if pattern.search(value) for site in sites]
        out.append(f'- {method} {path} {rel}:{line} <- {_sites(callers) if callers else "no Rust caller"}')
    return out


def _call_kinds(project, rust, server):
    header, server_values = [], {}
    for rel in server:
        tree = project.tree(rel)
        for node in ast.walk(tree) if tree else ():
            if isinstance(node, ast.ClassDef) and node.name == CALL_KIND:
                for stmt in node.body:
                    if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1
                            and isinstance(stmt.targets[0], ast.Name)
                            and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str)):
                        server_values.setdefault(stmt.value.value, []).append((rel, stmt.lineno))
            elif isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.lower() == CALL_HEADER:
                header.append(('py', rel, node.lineno))
    arms, variants, uses = {}, {}, {}
    for rel in rust:
        src = project.source(rel)
        header += [('rs', rel, src.line(offset)) for offset, value in src.strings.items()
                   if value.lower() == CALL_HEADER and not src.in_test(offset)]
        blocks = [(m.start(), _item_end(src.bare, m.end() - 1)) for m in CALL_IMPL.finditer(src.bare)]
        for start, end in blocks:
            for arm in CALL_ARM.finditer(src.bare, start, end):
                value = src.strings.get(arm.end())
                if value is not None:
                    arms.setdefault(value, []).append((rel, src.line(arm.start())))
                    variants.setdefault(arm.group(1), set()).add(value)
        for m in CALL_USE.finditer(src.bare):
            if not src.in_test(m.start()) and not any(start <= m.start() < end for start, end in blocks):
                uses.setdefault(m.group(1), []).append((rel, src.line(m.start())))
    if not header and not server_values and not arms:
        return []
    out = []
    _block(out, '### X-MetaMate-Call', f'The header names the kind of a proxy call: server `{CALL_KIND}` value (py) '
           f'and the Rust `{CALL_KIND}` variant that sends it (rs), then the Rust calls that use it.')
    if header:
        parts = [f'{side} {_sites([(rel, line) for s, rel, line in header if s == side])}'
                 for side in ('rs', 'py') if any(s == side for s, _, _ in header)]
        out.append('- header: ' + '; '.join(parts))
    for value in sorted(set(server_values) | set(arms)):
        sent = [site for variant, values in variants.items() if value in values for site in uses.get(variant, [])]
        parts = [f'{label} {_sites(sites)}' for label, sites in
                 (('py', server_values.get(value)), ('rs', arms.get(value)), ('used', sent)) if sites]
        out.append(f'- `{value}`: ' + '; '.join(parts))
    return out


def _locale_keys(project, rust_literals, ts_literals, ts=()):
    path = project.root / LOCALE
    try:
        keys = sorted(json.loads(path.read_text(encoding='utf-8-sig')))
    except (OSError, ValueError, TypeError):
        return []
    out, unused, ui = [], [], {}
    dynamic = {}
    for rel in ts:
        src = project.source(rel)
        for m in re.finditer(r'`([^`$\n]+)\$\{', src.code):
            # Only real template literals, never text within another string.
            if src.text[m.start()] == '`' and src.bare[m.start()] == '"':
                dynamic.setdefault(m.group(1), []).append((rel, src.line(m.start())))
    _block(out, '### Locale keys', f'Keys of {LOCALE}: Rust uses (rs) and keys without literal use are listed '
           'individually; TS-only keys are grouped by prefix. Literal template prefixes count as use.')
    for key in keys:
        ts_sites = ts_literals.get(key, []) + [site for prefix, sites in dynamic.items()
                                             if key.startswith(prefix) for site in sites]
        parts = [f'{side} {_sites(index[key])}' for side, index in (('rs', rust_literals), ('ts', {key: ts_sites} if ts_sites else {}))
                 if key in index]
        if key in rust_literals:
            out.append(f'- `{key}`: ' + '; '.join(parts))
        elif ts_sites:
            group = ui.setdefault(key.split('.')[0], [0, set()])
            group[0] += 1
            group[1].update(path for path, _ in ts_sites)
        else:
            unused.append(key)
    for prefix, (count, paths) in sorted(ui.items()):
        out.append(f'- `{prefix}.*` ({count} keys): ' + ', '.join(sorted(paths)))
    if unused:
        prefixes = ', '.join(f'`{prefix}.*`' for prefix in sorted({key.split('.')[0] for key in unused}))
        out.append(f'- no literal use ({len(unused)} keys); prefixes: {prefixes}')
        out += [f'- `{key}`: no literal use' for key in unused]
    return out


