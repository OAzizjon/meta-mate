RUST_TEST = re.compile(r'#\[\s*(?:\w+\s*::\s*)*test\b')
TS_TEST = re.compile(r'^[ \t]*(?:test|it)(?:\.(?:only|skip|todo))?\s*\(', re.M)


def _test_area(rel):
    parts = rel.split('/')
    return '/'.join(parts[:2]) if parts[0] == 'crates' else parts[0]


def _test_counts(project, rust):
    counts = {}
    for rel in project.files(*RUST_TESTS) + rust:
        counts[rel] = len(RUST_TEST.findall(project.source(rel).bare))
    for rel in project.files(*TS_TESTS):
        counts[rel] = len(TS_TEST.findall(project.source(rel).bare))
    for rel in project.files(*PY_TESTS):
        tree = project.tree(rel)
        counts[rel] = sum(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith('test')
                          for node in ast.walk(tree)) if tree else 0
    return counts


def _matching_tests(rel, counts):
    path = PurePosixPath(rel)
    stem = path.stem
    if path.suffix == '.rs':
        base = rel.split('/src/', 1)[0] + '/tests/'
        return sorted(test for test in counts if test == base + stem + '.rs' or test.startswith(base + stem + '/'))
    if path.suffix == '.ts':
        return [test for test in sorted(counts) if test == str(path.with_suffix('.test.ts'))]
    base = rel.split('/')[0] + '/tests/test_' + stem + '.py'
    return [base] if base in counts else []


def _tests_part(project, rust):
    counts = _test_counts(project, rust)
    areas = {}
    for rel, count in counts.items():
        if count:
            areas.setdefault(_test_area(rel), []).append((rel, count))
    out = []
    _block(out, '## Tests', 'Counts include standalone test files and source files with inline tests. '
           'Rust `#[test]`, TypeScript `test(`/`it(`, Python `test*` methods.')
    out += ['| Area | Tests | Files |', '|---|---:|---:|']
    order = {name: k for k, name in enumerate(TEST_AREAS)}
    for area in sorted(areas, key=lambda name: (order.get(name.split('/')[0], len(order)), name)):
        files = sorted(areas[area])
        out.append(f'| {area} | {sum(n for _, n in files)} | {len(files)} |')
    return out


# --- render, main --------------------------------------------------------------

def _block(out, heading, intro=None):
    if out and out[-1] != '':
        out.append('')
    out += [heading, '']
    if intro:
        out += [intro, '']


def render(root=ROOT):
    """The whole docs/code-map.md for the tree at `root`."""
    project = Project(root)
    sources, seen = [], set()
    for pattern, lang, area in SOURCES:
        for rel in project.files(pattern):
            if rel not in seen and not rel.endswith('.test.ts'):
                seen.add(rel)
                sources.append((area or '/'.join(rel.split('/')[:2]), rel, lang))
    rust = [rel for _, rel, lang in sources if lang == 'rust']
    ts = [rel for _, rel, lang in sources if lang == 'ts']
    server = [rel for area, rel, _ in sources if area == 'server/metamate_proxy']
    rust_literals, ts_literals = project.literals(rust), project.literals(ts)

    out = [HEADER, '# Code map', '', INTRO]
    _extend(out, _sources_part(project, sorted(sources, key=lambda s: (_area_rank(s[0]), s[0], s[1]))))
    links = [part for part in (_commands(project, rust, ts_literals), _channels(project, rust, ts),
                               _disk_files(project, rust), _events(project, rust, ts),
                               _routes(project, server, rust_literals), _call_kinds(project, rust, server),
                               _locale_keys(project, rust_literals, ts_literals, ts)) if part]
    if links:
        _block(out, '## Cross-language links')
        for part in links:
            _extend(out, part)
    _extend(out, _tests_part(project, rust))
    while out[-1] == '':
        out.pop()
    return '\n'.join(out) + '\n'


def _extend(out, part):
    if part and out[-1] != '':
        out.append('')
    out += part


def _area_rank(area):
    """Areas in the order of SOURCES; the crates sort by name."""
    for k, (pattern, _, name) in enumerate(SOURCES):
        if area == name or (name is None and area.startswith(pattern.split('/')[0] + '/')):
            return k
    return len(SOURCES)


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(prog='mm map', description='Write docs/code-map.md (see the module docstring).')
    parser.add_argument('--check', action='store_true', help='exit 1 when docs/code-map.md is stale')
    args = parser.parse_args(argv)
    root = Path(root)
    text = render(root)
    target = root / OUTPUT
    try:
        current = target.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        current = None
    if current == text:
        print(f'{OUTPUT}: up to date')
        return 0
    if args.check:
        print(f'{OUTPUT} is stale: run `mm map`')
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT} ({text.count(chr(10))} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
